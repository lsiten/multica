CREATE TABLE meeting_session (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    workspace_id UUID NOT NULL,
    creator_id UUID NOT NULL,
    source_type TEXT NOT NULL DEFAULT 'workspace' CHECK (source_type IN ('workspace', 'chat', 'group')),
    source_chat_session_id UUID,
    source_agent_id UUID,
    runtime_id UUID,
    status TEXT NOT NULL DEFAULT 'recording' CHECK (status IN ('recording', 'paused', 'finalizing', 'organizing', 'ready', 'failed', 'cancelled')),
    language TEXT NOT NULL DEFAULT 'zh',
    title TEXT NOT NULL DEFAULT '',
    timezone TEXT NOT NULL DEFAULT 'Asia/Shanghai',
    started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ended_at TIMESTAMPTZ,
    audio_retention TEXT NOT NULL DEFAULT 'discard' CHECK (audio_retention IN ('discard', 'retain')),
    project_id UUID,
    topic TEXT NOT NULL DEFAULT '',
    transcript TEXT NOT NULL DEFAULT '',
    summary TEXT NOT NULL DEFAULT '',
    decisions JSONB NOT NULL DEFAULT '[]'::jsonb,
    action_items JSONB NOT NULL DEFAULT '[]'::jsonb,
    classification JSONB NOT NULL DEFAULT '{}'::jsonb,
    failure_reason TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
